    fun traducir(texto: String?): String {
        if (texto.isNullOrBlank()) return "No especificado"
        var resultado = texto.lowercase().trim()

        val diccionarioOrdenado = diccionario.entries.sortedByDescending { it.key.length }

        diccionarioOrdenado.forEach { (eng, esp) ->
            val regex = Regex("\\b${Regex.escape(eng)}\\b", RegexOption.IGNORE_CASE)
            resultado = resultado.replace(regex, esp)
        }

        return resultado.replaceFirstChar { it.uppercase() }
    }
